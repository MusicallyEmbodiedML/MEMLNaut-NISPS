#!/usr/bin/env python3
"""Turn a 16-bit PCM WAV into a C++ header, to compile a short sample into a firmware.

    scripts/wav2header.py samples/bd2.wav modes/AudioApps/samples/bd2.h

Stereo is mixed to mono. The array is named after the input file (bd2_samples).
"""
import argparse
import array
import re
import sys
import wave
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("wav", type=Path)
    ap.add_argument("header", type=Path)
    args = ap.parse_args()

    with wave.open(str(args.wav)) as w:
        channels, width, rate, frames = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        if width != 2:
            sys.exit(f"{args.wav}: expected 16-bit samples, found {width * 8}-bit")
        data = array.array("h", w.readframes(frames))
    if sys.byteorder == "big":
        data.byteswap()
    if channels > 1:
        data = array.array("h", (sum(data[i:i + channels]) // channels
                                 for i in range(0, len(data), channels)))

    name = re.sub(r"\W", "_", args.wav.stem)
    if name[0].isdigit():
        name = "s_" + name
    lines = [", ".join(str(v) for v in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(lines)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(f"""// Generated by scripts/wav2header.py from {args.wav.name}. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>

static constexpr float {name}_sampleRate = {rate}.f;
static constexpr size_t {name}_length = {len(data)};
// Not const, so it's copied to RAM at boot: reading it can't stall on flash.
static int16_t {name}_samples[{name}_length] = {{
    {body}
}};
""")
    print(f"{args.header}: {len(data)} samples, {rate} Hz, {len(data) * 2} bytes")


if __name__ == "__main__":
    main()
